#!/usr/bin/env node
// Builds the offline screenshot gallery used for visual review.
//
// Reads `tests/visual/baselines/` and writes `tests/visual/gallery/index.html`.
// The page is static: no scripts, no remote fonts, no network access.

import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const uiDir = resolve(scriptDir, '..');
const baselines = join(uiDir, 'tests', 'visual', 'baselines');
const galleryDir = join(uiDir, 'tests', 'visual', 'gallery');

/** Escapes text for HTML. */
function escapeHtml(value) {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

/** Recursively lists PNG files relative to the baseline root. */
function collect(directory, prefix = '') {
  return readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) {
        return statSync(full).isDirectory()
          ? collect(full, prefix === '' ? entry.name : `${prefix}/${entry.name}`)
          : [];
      }
      return entry.name.endsWith('.png') ? [prefix === '' ? entry.name : `${prefix}/${entry.name}`] : [];
    })
    .sort();
}

const files = collect(baselines);
const matrixName = /^(?<screen>.+)-(?<theme>dark|light)-(?<dpi>100|125|150|200)-(?<language>ru|en)\.png$/;
const matrix = files.filter((file) => matrixName.test(file));
const curated = files.filter((file) => !matrixName.test(file));

const byScreen = new Map();
for (const file of matrix) {
  const screen = matrixName.exec(file)?.groups?.screen ?? 'unknown';
  const items = byScreen.get(screen) ?? [];
  items.push(file);
  byScreen.set(screen, items);
}

function figure(file, title) {
  const src = relative(galleryDir, join(baselines, file)).replaceAll('\\', '/');
  return `
      <figure>
        <a href="${escapeHtml(src)}"><img loading="lazy" src="${escapeHtml(src)}" alt="${escapeHtml(title)}"></a>
        <figcaption>${escapeHtml(title)}</figcaption>
      </figure>`;
}

const screenSections = [...byScreen.entries()]
  .map(
    ([screen, items]) => `
    <section id="screen-${escapeHtml(screen)}">
      <h2>${escapeHtml(screen)}</h2>
      <div class="grid">${items.map((file) => figure(file, file.replace(new RegExp(`^${screen}-`), '').replace('.png', ''))).join('')}
      </div>
    </section>`,
  )
  .join('\n');

const curatedSection = `
    <section id="curated">
      <h2>Curated delivery batches</h2>
      <div class="grid">${curated.map((file) => figure(file, file.replace('.png', ''))).join('')}
      </div>
    </section>`;

const navigation = [...byScreen.keys()]
  .map((screen) => `<li><a href="#screen-${escapeHtml(screen)}">${escapeHtml(screen)}</a></li>`)
  .join('');

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <title>FreeSpace visual baselines</title>
    <style>
      :root { color-scheme: light dark; font-family: "Segoe UI", system-ui, sans-serif; }
      body { margin: 0 auto; max-width: 1200px; padding: 24px; }
      h1 { font-size: 22px; }
      h2 { font-size: 16px; margin-block: 28px 12px; text-transform: capitalize; }
      ul { columns: 6; padding-left: 18px; }
      .grid { display: grid; grid-template-columns: repeat(auto-fill, minmax(220px, 1fr)); gap: 12px; }
      figure { margin: 0; }
      img { width: 100%; height: auto; border: 1px solid currentColor; border-radius: 4px; }
      figcaption { font-size: 12px; opacity: .75; margin-top: 4px; }
    </style>
  </head>
  <body>
    <h1>FreeSpace visual baselines</h1>
    <p>${String(files.length)} references: full matrix 24 screens × 2 themes × 4 DPI × 2 languages, plus curated states. Generated by <code>npm run gallery</code>.</p>
    <nav><ul>${navigation}</ul></nav>
${screenSections}
${curatedSection}
  </body>
</html>
`;

mkdirSync(galleryDir, { recursive: true });
writeFileSync(join(galleryDir, 'index.html'), html, 'utf8');
console.log(`Gallery written to ${join(galleryDir, 'index.html')} (${String(files.length)} images)`);
